"""한국어 음식점 글 감성 사전 — **실행 전에 고정하고 커밋한다**.

이 파일을 결과를 보고 고치는 것이 감성 실험의 가장 큰 사후 선택 위험이다.
단어를 추가하거나 빼면 부정 비율이 바뀌고, 그러면 원하는 결론 쪽으로 얼마든지
움직일 수 있다. 그래서 결과와 함께 이 파일의 커밋 해시를 기록한다.

수록 원칙 (실행 전 고정):
  1. 음식점 글에서 화자의 평가를 직접 드러내는 표현만 넣는다.
  2. **양가적인 말은 넣지 않는다.** "웨이팅"은 불만이면서 동시에 인기의
     지표라 어느 쪽으로도 셀 수 없다. "매운"도 취향이지 평가가 아니다.
  3. 어간만 적는다. 한국어 활용을 정규식 없이 부분일치로 잡기 위해서다
     ("맛있" 하나로 맛있다/맛있어요/맛있었는데 전부 걸린다).
  4. 입지 관련 어휘는 여기 넣지 않는다 — ABSA(H-3)의 대상이지 전반 감성이
     아니다.
"""

POS = (
    "맛있", "맛집", "존맛", "꿀맛", "최고", "훌륭", "만족", "추천드",
    "강추", "재방문", "또 가", "또가", "인생", "감동", "완벽", "굿",
    "친절", "깔끔", "정갈", "신선", "푸짐", "넉넉", "가성비", "혜자",
    "분위기 좋", "분위기좋", "좋았", "좋아요", "좋더", "괜찮았", "대박",
)

NEG = (
    "별로", "실망", "최악", "불친절", "무례", "비추", "다신 안", "다신안",
    "안 갈", "안갈", "아쉬웠", "아쉽", "그저 그", "그저그", "밍밍",
    "느끼했", "짜게", "너무 짜", "비렸", "질겼", "눅눅", "식었",
    "불결", "더럽", "지저분", "위생",
    "비싸", "비쌌", "가격이 좀", "돈 아깝", "돈아깝",
    "시끄러", "정신없", "불쾌", "화가", "황당",
)

# 프롬프트도 여기 고정한다. LLM 검증에 쓰며, 결과와 함께 커밋된 이 문자열이
# 그대로 쓰였음을 재현자가 확인할 수 있어야 한다.
LLM_PROMPT = (
    "다음은 한국어 음식점 관련 블로그 글의 일부다. "
    "글쓴이가 그 가게에 대해 드러낸 전반적 평가를 판정하라. "
    "positive / negative / neutral 중 하나만 소문자로 답하라. "
    "가게에 대한 평가가 드러나지 않으면 neutral.\n\n글: "
)


def score(text):
    """-> (pos_hits, neg_hits, label). label ∈ {pos, neg, neu}"""
    t = (text or "").lower()
    p = sum(1 for w in POS if w in t)
    n = sum(1 for w in NEG if w in t)
    if p > n:
        return p, n, "pos"
    if n > p:
        return p, n, "neg"
    return p, n, "neu"


if __name__ == "__main__":
    for s in ("음식은 맛있는데 주차가 너무 불편해요",
              "여기 진짜 별로였어요 다신 안 갈 듯",
              "친절하고 깔끔했습니다 재방문 의사 있어요",
              "연남동 골목에 있는 가게입니다"):
        print(f"{score(s)}  {s}")
